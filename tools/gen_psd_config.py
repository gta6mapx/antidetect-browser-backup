#!/usr/bin/env python3
"""Generate a profile-sync-daemon "browser definition" for antidetect profiles.

profile-sync-daemon (psd, MIT, https://github.com/graysky2/profile-sync-daemon)
is a Linux-only systemd user service. It cannot be launched from inside the
Python app; the server admin installs it once and manages it via psd.conf.

psd discovers profile dirs from per-"browser" definition files under
/usr/share/psd/browsers/<name>, each of which sets a DIRArr bash array of
full profile-dir paths. psd.conf itself only selects browsers via the
BROWSERS=() array, so per-profile dirs do NOT go into psd.conf.

This script enumerates the antidetect profile dirs (honoring ANTIDETECT_HOME
via src/paths.py) and prints a ready-to-install browser definition to stdout:

    python3 tools/gen_psd_config.py > /tmp/psd-antidetect
    sudo install -m 644 /tmp/psd-antidetect /usr/share/psd/browsers/antidetect
    # then in ~/.config/psd/psd.conf:  BROWSERS=(antidetect)
    systemctl --user restart psd.service
"""

import argparse
import os
import shlex
import sys

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, REPO_ROOT)

from src import paths  # noqa: E402  (import after sys.path fixup)


def find_profile_dirs() -> list[str]:
    """Return sorted full paths of all real profile directories."""
    root = paths.profiles_dir()
    if not os.path.isdir(root):
        return []
    dirs = []
    for name in sorted(os.listdir(root)):
        full = os.path.join(root, name)
        # Skip files, symlinks (psd refuses to manage symlinked profiles),
        # and junk like .DS_Store / __pycache__.
        if os.path.isdir(full) and not os.path.islink(full) and not name.startswith("."):
            dirs.append(os.path.abspath(full))
    return dirs


def render(browser_name: str, dirs: list[str]) -> str:
    """Render the psd browser-definition file content."""
    lines = [
        f"# psd browser definition for the antidetect browser ({browser_name})",
        "# Generated by tools/gen_psd_config.py - DO NOT EDIT BY HAND.",
        "# Re-run the generator and reinstall whenever profiles are added/removed.",
        "#",
        "# Install (Linux server only - needs root, one time per regeneration):",
        f"#   sudo install -m 644 <this-file> /usr/share/psd/browsers/{browser_name}",
        "#",
        "# Then select it in ~/.config/psd/psd.conf:",
        f"#   BROWSERS=({browser_name})",
        "#",
        "# Full setup: see docs/PROFILE_SYNC_DAEMON.md",
        "# NOTE: Linux server only - profile-sync-daemon does not run on Windows.",
        "",
        # PSNAME is the process name psd greps for to refuse startup while a
        # managed browser is running. Our profiles are launched by Camoufox
        # instances with varying process names, so leave it empty (psd skips
        # the running check then) and rely on the doc's "close browsers first"
        # rule instead.
        'PSNAME=""',
        "DIRArr=(",
    ]
    for d in dirs:
        lines.append(shlex.quote(d))
    lines.append(")")
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        prog="gen_psd_config.py",
        description=(
            "Enumerate antidetect profile dirs (honoring ANTIDETECT_HOME) and "
            "print a profile-sync-daemon browser-definition file to stdout. "
            "Install it with: sudo install -m 644 <out> /usr/share/psd/browsers/<name> "
            "and add <name> to BROWSERS=() in ~/.config/psd/psd.conf."
        ),
    )
    ap.add_argument(
        "--browser-name",
        default="antidetect",
        help="Name of the psd browser definition (default: %(default)s). "
        "Must match the filename installed under /usr/share/psd/browsers/ "
        "and the entry added to BROWSERS=() in psd.conf.",
    )
    ap.add_argument(
        "--count",
        action="store_true",
        help="Only print the number of profile dirs found (no definition).",
    )
    args = ap.parse_args(argv)

    dirs = find_profile_dirs()

    if args.count:
        print(len(dirs))
        return 0

    if not dirs:
        print(
            f"gen_psd_config.py: no profile dirs found under {paths.profiles_dir()!r}; "
            "nothing to emit.",
            file=sys.stderr,
        )
        return 1

    sys.stdout.write(render(args.browser_name, dirs))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
